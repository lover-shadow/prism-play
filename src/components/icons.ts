export type IconName = keyof typeof SHAPES;

export const ICON_NAMES = Object.keys(SHAPES) as IconName[];

export interface IconOptions {
  size?: IconSize;
  /** When set the icon is announced; otherwise it is decorative and hidden from assistive tech. */
  label?: string;
  className?: string;
}

function isIconSize(value: number): value is IconSize {
  return (ICON_SIZES as readonly number[]).includes(value);
}

/** Returns an inline SVG string. Values come from a closed table, so no caller input reaches the markup. */
export function icon(name: IconName, options: IconOptions = {}): string {
  const shapes = SHAPES[name];
  if (shapes === undefined) throw new Error(`未知图标：${String(name)}（仅允许 components/icons.ts 内置表）`);
  const size = options.size ?? 20;
  if (!isIconSize(size)) throw new Error(`图标尺寸只能取 ${ICON_SIZES.join('/')}px，收到 ${size}`);
  const a11y =
    options.label === undefined
      ? 'aria-hidden="true" focusable="false"'
      : `role="img" aria-label="${escapeAttribute(options.label)}"`;
  const className = options.className === undefined ? '' : ` class="${escapeAttribute(options.className)}"`;
  return (
    `<svg${className} width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" ` +
    `stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${shapes}</svg>`
  );
}

function escapeAttribute(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');
}
